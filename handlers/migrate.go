type MigrateRequest struct {
	ArchivePath string `json:"archive_path"`
}

type LsaFolder struct {
	Name        string `json:"Name"`
	AccentColor string `json:"AccentColor"`
	Description string `json:"Description"`
}

type LsaCollection struct {
	Name        string      `json:"Name"`
	AccentColor string      `json:"AccentColor"`
	Description string      `json:"Description"`
	Folders     []LsaFolder `json:"Folders"`
}

type LsaMediaItem struct {
	Name string `json:"name"`
	Type string `json:"type"`
	Path string `json:"path"`
}

type LsaPost struct {
	ID           string         `json:"id"`
	AuthorName   string         `json:"authorName"`
	AuthorHandle string         `json:"authorHandle"`
	Content      string         `json:"content"`
	Comment      *string        `json:"comment"`
	PostDate     string         `json:"postDate"`
	FolderName   string         `json:"folderName"`
	Tags         []string       `json:"tags"`
	MediaFiles   []LsaMediaItem `json:"mediaFiles"`
}

// stripBOM removes the UTF-8 Byte Order Mark (0xEF, 0xBB, 0xBF) generated by .NET / C# Encoding.UTF8
func stripBOM(b []byte) []byte {
	return bytes.TrimPrefix(b, []byte("\xef\xbb\xbf"))
}

func isMediaExtension(ext string) bool {
	lower := strings.ToLower(ext)
	switch lower {
	case ".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp", ".jfif", ".avif", ".heic", ".heif", ".svg", ".ico", ".tiff", ".tif", ".mp4", ".webm", ".mov", ".mkv", ".m4v", ".ogg", ".ogv":
		return true
	default:
		return false
	}
}

// resolveMediaFilePath tries multiple strategies to locate media across different PCs and directories
func resolveMediaFilePath(archivePath, subDirPath, rawPath, fileName string) string {
	// 1. Direct file inside the specific subfolder
	if fileName != "" && subDirPath != "" {
		candidate := filepath.Join(subDirPath, fileName)
		if fi, err := os.Stat(candidate); err == nil && !fi.IsDir() {
			return candidate
		}
	}

	// 2. Exact rawPath on this machine (if still exists)
	if rawPath != "" {
		if fi, err := os.Stat(rawPath); err == nil && !fi.IsDir() {
			return rawPath
		}

		// 3. Subpath relative to "Media" or "LocalSocialArchive"
		normalized := filepath.ToSlash(rawPath)
		for _, marker := range []string{"/media/", "/localsocialarchive/media/"} {
			idx := strings.Index(strings.ToLower(normalized), marker)
			if idx != -1 {
				rel := normalized[idx+len(marker):]
				candidate := filepath.Join(archivePath, "Media", filepath.FromSlash(rel))
				if fi, err := os.Stat(candidate); err == nil && !fi.IsDir() {
					return candidate
				}
			}
		}

		// 4. Match by base filename inside the post subfolder
		baseName := filepath.Base(rawPath)
		if subDirPath != "" && baseName != "" {
			candidate := filepath.Join(subDirPath, baseName)
			if fi, err := os.Stat(candidate); err == nil && !fi.IsDir() {
				return candidate
			}
		}

		// 5. Match by base filename in the root archive Media folder
		if baseName != "" {
			candidate := filepath.Join(archivePath, "Media", baseName)
			if fi, err := os.Stat(candidate); err == nil && !fi.IsDir() {
				return candidate
			}
		}
	}

	return ""
}

// MigrateLocalSocialArchive imports spaces, folders, tweets, and media files from an existing LocalSocialArchive folder
func MigrateLocalSocialArchive(w http.ResponseWriter, r *http.Request) {
	var req MigrateRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil && err != io.EOF {
		writeError(w, http.StatusBadRequest, "Invalid request body: "+err.Error())
		return
	}

	archivePath := strings.TrimSpace(req.ArchivePath)
	if archivePath == "" {
		homeDir, err := os.UserHomeDir()
		if err == nil {
			// Check LocalAppData first (latest app location)
			appDataLocal := filepath.Join(homeDir, "AppData", "Local", "LocalSocialArchive")
			if fi, err := os.Stat(appDataLocal); err == nil && fi.IsDir() {
				archivePath = appDataLocal
			} else {
				// Fallback to Documents
				archivePath = filepath.Join(homeDir, "Documents", "LocalSocialArchive")
			}
		}
	}

	if _, err := os.Stat(archivePath); err != nil {
		writeError(w, http.StatusBadRequest, fmt.Sprintf("Directory not found at '%s'", archivePath))
		return
	}

	// Check if user selected or passed a parent directory that contains a nested "LocalSocialArchive" folder
	nestedCandidate := filepath.Join(archivePath, "LocalSocialArchive")
	if fi, err := os.Stat(nestedCandidate); err == nil && fi.IsDir() {
		if _, err := os.Stat(filepath.Join(nestedCandidate, "Media")); err == nil {
			archivePath = nestedCandidate
		} else if _, err := os.Stat(filepath.Join(nestedCandidate, "collections_config.json")); err == nil {
			archivePath = nestedCandidate
		}
	}

	destMediaDir, err := database.GetMediaDir()
	if err != nil {
		writeError(w, http.StatusInternalServerError, "Failed to get TweetVault media directory: "+err.Error())
		return
	}

	spacesCreated := 0
	foldersCreated := 0
	postsImported := 0
	mediaFilesCopied := 0

	// 1. Folder & Space mappings
	folderToID := make(map[string]int64)
	folderToSpaceID := make(map[string]int64)

	var defaultSpaceID int64 = 1
	var defaultFolderID int64 = 1
	database.DB.QueryRow("SELECT id FROM spaces ORDER BY id ASC LIMIT 1").Scan(&defaultSpaceID)
	database.DB.QueryRow("SELECT id FROM folders ORDER BY id ASC LIMIT 1").Scan(&defaultFolderID)

	// 2. Read collections_config.json (handling UTF-8 BOM)
	configPath := filepath.Join(archivePath, "collections_config.json")
	if configBytes, err := os.ReadFile(configPath); err == nil {
		cleanConfigBytes := stripBOM(configBytes)
		var collections []LsaCollection
		if err := json.Unmarshal(cleanConfigBytes, &collections); err == nil {
			for _, col := range collections {
				colName := strings.TrimSpace(col.Name)
				if colName == "" {
					continue
				}

				var spaceID int64
				err := database.DB.QueryRow("SELECT id FROM spaces WHERE LOWER(name) = LOWER(?)", colName).Scan(&spaceID)
				if err != nil {
					color := col.AccentColor
					if color == "" {
						color = "#a8c7fa"
					}
					res, err := database.DB.Exec(
						"INSERT INTO spaces (name, description, color, icon) VALUES (?, ?, ?, 'space')",
						colName, col.Description, color,
					)
					if err == nil {
						spaceID, _ = res.LastInsertId()
						spacesCreated++
					} else {
						spaceID = defaultSpaceID
					}
				}

				for _, f := range col.Folders {
					fName := strings.TrimSpace(f.Name)
					if fName == "" {
						continue
					}

					var fID int64
					err := database.DB.QueryRow(
						"SELECT id FROM folders WHERE space_id = ? AND LOWER(name) = LOWER(?)",
						spaceID, fName,
					).Scan(&fID)
					if err != nil {
						color := f.AccentColor
						if color == "" {
							color = "#a8c7fa"
						}
						res, err := database.DB.Exec(
							"INSERT INTO folders (space_id, name, color) VALUES (?, ?, ?)",
							spaceID, fName, color,
						)
						if err == nil {
							fID, _ = res.LastInsertId()
							foldersCreated++
						}
					}

					if fID > 0 {
						folderToID[strings.ToLower(fName)] = fID
						folderToSpaceID[strings.ToLower(fName)] = spaceID
					}
				}
			}
		}
	}

	importedPostHashes := make(map[string]bool)

	// 3. If ArchiveData.db (SQLite) exists, import directly from SQLite database for maximum fidelity
	archiveSqlitePath := filepath.Join(archivePath, "ArchiveData.db")
	if _, err := os.Stat(archiveSqlitePath); err == nil {
		if srcDb, err := sql.Open("sqlite", archiveSqlitePath+"?mode=ro"); err == nil {
			defer srcDb.Close()

			rows, qErr := srcDb.Query(`
				SELECT Id, AuthorName, AuthorHandle, Content, PostDate, FolderName, Tags, Comment, CreatedAt 
				FROM Posts
			`)
			if qErr == nil {
				defer rows.Close()

				for rows.Next() {
					var id, authorName, authorHandle, content, postDate, folderName, tags, createdAt string
					var comment sql.NullString

					if err := rows.Scan(&id, &authorName, &authorHandle, &content, &postDate, &folderName, &tags, &comment, &createdAt); err == nil {
						content = strings.TrimSpace(content)
						if content == "" {
							content = "Archived Post"
						}

						// Fetch media items for this post
						var localMediaURLs []string
						mRows, mErr := srcDb.Query("SELECT FilePath FROM Media WHERE PostId = ?", id)
						if mErr == nil {
							for mRows.Next() {
								var filePath string
								if mRows.Scan(&filePath) == nil && filePath != "" {
									resolvedFile := resolveMediaFilePath(archivePath, "", filePath, filepath.Base(filePath))
									if resolvedFile != "" {
										ext := filepath.Ext(resolvedFile)
										if ext == "" {
											ext = ".png"
										}
										destFileName := fmt.Sprintf("lsa_db_%s_%s%s", id[:min(8, len(id))], randomHex(4), ext)
										destFilePath := filepath.Join(destMediaDir, destFileName)
										if copyFile(resolvedFile, destFilePath) == nil {
											localMediaURLs = append(localMediaURLs, "/api/media/"+destFileName)
											mediaFilesCopied++
										}
									}
								}
							}
							mRows.Close()
						}

						targetFolderID := defaultFolderID
						targetSpaceID := defaultSpaceID
						fKey := strings.ToLower(strings.TrimSpace(folderName))
						if fID, exists := folderToID[fKey]; exists {
							targetFolderID = fID
							targetSpaceID = folderToSpaceID[fKey]
						}

						mediaUrlCol := ""
						if len(localMediaURLs) == 1 {
							mediaUrlCol = localMediaURLs[0]
						} else if len(localMediaURLs) > 1 {
							if b, err := json.Marshal(localMediaURLs); err == nil {
								mediaUrlCol = string(b)
							}
						}

						authorName = strings.TrimSpace(authorName)
						if authorName == "" {
							authorName = "Offline User"
						}
						authorHandle = strings.TrimSpace(authorHandle)
						if authorHandle == "" {
							authorHandle = "@offline"
						}

						tagsJson := "[]"
						if tags != "" {
							var tagList []string
							for _, t := range strings.Fields(tags) {
								tagList = append(tagList, strings.TrimPrefix(t, "#"))
							}
							if b, err := json.Marshal(tagList); err == nil {
								tagsJson = string(b)
							}
						}

						commentStr := ""
						if comment.Valid {
							commentStr = comment.String
						}

						if postDate == "" {
							postDate = createdAt
						}
						if postDate == "" {
							postDate = "2026-10-10 12:00:00"
						}

						var existingID int64
						checkErr := database.DB.QueryRow(
							"SELECT id FROM posts WHERE content = ? AND author_handle = ?",
							content, authorHandle,
						).Scan(&existingID)

						if checkErr != nil {
							_, insertErr := database.DB.Exec(`
								INSERT INTO posts (
									space_id, folder_id, type, title, content, author_name, author_handle,
									media_url, tags, comment, created_at, updated_at
								) VALUES (?, ?, 'tweet', '', ?, ?, ?, ?, ?, ?, ?, ?)
							`,
								targetSpaceID, targetFolderID, content, authorName, authorHandle,
								mediaUrlCol, tagsJson, commentStr, postDate, postDate,
							)
							if insertErr == nil {
								postsImported++
								importedPostHashes[content+authorHandle] = true
							}
						} else {
							// Update media_url if missing
							if mediaUrlCol != "" {
								database.DB.Exec("UPDATE posts SET media_url = ? WHERE id = ? AND (media_url IS NULL OR media_url = '')", mediaUrlCol, existingID)
							}
							importedPostHashes[content+authorHandle] = true
						}
					}
				}
			}
		}
	}

	// 4. Scan Media directory subfolders for post.json & media attachments
	mediaSourceDir := filepath.Join(archivePath, "Media")
	entries, err := os.ReadDir(mediaSourceDir)
	if err == nil {
		for _, entry := range entries {
			if !entry.IsDir() {
				continue
			}

			subDirPath := filepath.Join(mediaSourceDir, entry.Name())
			postJsonPath := filepath.Join(subDirPath, "post.json")

			var lsaPost LsaPost
			hasPostJson := false

			if jsonBytes, err := os.ReadFile(postJsonPath); err == nil {
				cleanBytes := stripBOM(jsonBytes)
				if err := json.Unmarshal(cleanBytes, &lsaPost); err == nil {
					hasPostJson = true
				}
			}

			content := strings.TrimSpace(lsaPost.Content)
			if !hasPostJson && content == "" {
				// Check if there are media files inside this directory even without post.json
				subFiles, _ := os.ReadDir(subDirPath)
				hasMediaInside := false
				for _, sf := range subFiles {
					if !sf.IsDir() && isMediaExtension(filepath.Ext(sf.Name())) {
						hasMediaInside = true
						break
					}
				}
				if !hasMediaInside {
					continue
				}
				content = "Archived Media Snapshot"
			}

			authorName := strings.TrimSpace(lsaPost.AuthorName)
			if authorName == "" {
				authorName = "Offline User"
			}
			authorHandle := strings.TrimSpace(lsaPost.AuthorHandle)
			if authorHandle == "" {
				authorHandle = "@offline"
			}

			// Skip if already imported via SQLite
			if importedPostHashes[content+authorHandle] {
				continue
			}

			// Copy all media files associated with this folder
			var localMediaURLs []string

			// A. First check mediaFiles array in post.json
			for _, m := range lsaPost.MediaFiles {
				resolvedFile := resolveMediaFilePath(archivePath, subDirPath, m.Path, m.Name)
				if resolvedFile != "" {
					ext := filepath.Ext(resolvedFile)
					if ext == "" {
						ext = ".png"
					}
					targetFileName := fmt.Sprintf("lsa_%s_%s", entry.Name(), filepath.Base(resolvedFile))
					destFilePath := filepath.Join(destMediaDir, targetFileName)

					if copyFile(resolvedFile, destFilePath) == nil {
						localMediaURLs = append(localMediaURLs, "/api/media/"+targetFileName)
						mediaFilesCopied++
					}
				}
			}

			// B. Also scan directory directly for any media files not listed in post.json
			if dirFiles, err := os.ReadDir(subDirPath); err == nil {
				for _, df := range dirFiles {
					if df.IsDir() {
						continue
					}
					ext := filepath.Ext(df.Name())
					if isMediaExtension(ext) {
						targetFileName := fmt.Sprintf("lsa_%s_%s", entry.Name(), df.Name())
						destFilePath := filepath.Join(destMediaDir, targetFileName)

						// Avoid duplicating if already copied
						alreadyAdded := false
						for _, u := range localMediaURLs {
							if strings.HasSuffix(u, targetFileName) {
								alreadyAdded = true
								break
							}
						}

						if !alreadyAdded {
							srcFile := filepath.Join(subDirPath, df.Name())
							if copyFile(srcFile, destFilePath) == nil {
								localMediaURLs = append(localMediaURLs, "/api/media/"+targetFileName)
								mediaFilesCopied++
							}
						}
					}
				}
			}

			targetFolderID := defaultFolderID
			targetSpaceID := defaultSpaceID

			fKey := strings.ToLower(strings.TrimSpace(lsaPost.FolderName))
			if fID, exists := folderToID[fKey]; exists {
				targetFolderID = fID
				targetSpaceID = folderToSpaceID[fKey]
			}

			mediaUrlCol := ""
			if len(localMediaURLs) == 1 {
				mediaUrlCol = localMediaURLs[0]
			} else if len(localMediaURLs) > 1 {
				if b, err := json.Marshal(localMediaURLs); err == nil {
					mediaUrlCol = string(b)
				}
			}

			tagsJson := "[]"
			if len(lsaPost.Tags) > 0 {
				if b, err := json.Marshal(lsaPost.Tags); err == nil {
					tagsJson = string(b)
				}
			}

			commentStr := ""
			if lsaPost.Comment != nil {
				commentStr = *lsaPost.Comment
			}

			createdAt := lsaPost.PostDate
			if createdAt == "" {
				createdAt = "2026-10-10 12:00:00"
			}

			var existingID int64
			err = database.DB.QueryRow(
				"SELECT id FROM posts WHERE content = ? AND author_handle = ?",
				content, authorHandle,
			).Scan(&existingID)

			if err != nil {
				_, insertErr := database.DB.Exec(`
					INSERT INTO posts (
						space_id, folder_id, type, title, content, author_name, author_handle,
						media_url, tags, comment, created_at, updated_at
					) VALUES (?, ?, 'tweet', '', ?, ?, ?, ?, ?, ?, ?, ?)
				`,
					targetSpaceID, targetFolderID, content, authorName, authorHandle,
					mediaUrlCol, tagsJson, commentStr, createdAt, createdAt,
				)

				if insertErr == nil {
					postsImported++
					importedPostHashes[content+authorHandle] = true
				}
			} else {
				if mediaUrlCol != "" {
					database.DB.Exec("UPDATE posts SET media_url = ? WHERE id = ? AND (media_url IS NULL OR media_url = '')", mediaUrlCol, existingID)
				}
				importedPostHashes[content+authorHandle] = true
			}
		}
	}

	writeJSON(w, http.StatusOK, map[string]any{
		"success":            true,
		"archive_path":       archivePath,
		"spaces_created":     spacesCreated,
		"folders_created":    foldersCreated,
		"posts_imported":     postsImported,
		"media_files_copied": mediaFilesCopied,
		"message": fmt.Sprintf(
			"Successfully imported %d posts, created %d spaces, %d folders, and copied %d media assets.",
			postsImported, spacesCreated, foldersCreated, mediaFilesCopied,
		),
	})
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()

	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer out.Close()

	_, err = io.Copy(out, in)
	return err
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
